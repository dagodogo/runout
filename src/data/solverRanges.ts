/** Expand a 13x13 grid to the solver's 1326 combo weights (pairs 6 combos, suited 4, offsuit 12). */
export function expandTo1326(grid: RangeGrid): Float32Array {
  const out = new Float32Array(1326);
  for (let r = 0; r < 13; r++) {
    for (let c = 0; c < 13; c++) {
      const w = grid[r][c];
      if (w === 0) continue;
      const hi = 12 - Math.min(r, c);
      const lo = 12 - Math.max(r, c);
      for (let s1 = 0; s1 < 4; s1++) {
        for (let s2 = 0; s2 < 4; s2++) {
          const pair = r === c;
          const suited = r < c;
          if (pair ? s1 >= s2 : suited ? s1 !== s2 : s1 === s2) continue;
          out[pairIndex(4 * hi + s1, 4 * lo + s2)] = w;
        }
      }
    }
  }
  return out;
}
